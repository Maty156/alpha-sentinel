/* pages/reports.js - OWNER: the Reports page - a date range + Generate button that
   renders /api/report into the page, and a Print button (window.print). Read-only,
   honest: when there is no data the report says so, it never invents numbers. */
(function () {
  'use strict';
  var S = window.Sentinel = window.Sentinel || {};
  S.pages = S.pages || {};
  var report = null;
  var errorMsg = '';

  function isoDay(d) {
    var p = function (n) { return (n < 10 ? '0' : '') + n; };
    return d.getFullYear() + '-' + p(d.getMonth() + 1) + '-' + p(d.getDate());
  }

  function defaults() {
    var to = new Date();
    var from = new Date(to.getTime() - 24 * 3600 * 1000);
    return { from: isoDay(from), to: isoDay(to) };
  }

  function summaryParagraph(r) {
    var s = r.summary || {};
    var total = (s.bySeverity ? Object.keys(s.bySeverity).reduce(function (a, k) { return a + (s.bySeverity[k] || 0); }, 0) : 0);
    var parts = [];
    parts.push('Between ' + r.period.from + ' and ' + r.period.to + ' the monitor raised ' + total + ' alert(s)');
    if (s.bySeverity && (s.bySeverity.Critical || 0) > 0) { parts.push(s.bySeverity.Critical + ' of them critical'); }
    if (s.bySeverity && (s.bySeverity.High || 0) > 0) { parts.push(s.bySeverity.High + ' high'); }
    var hosts = (s.hosts || 0);
    parts.push('across ' + hosts + ' host' + (hosts === 1 ? '' : 's') + ' and ' + (s.accounts || 0) + ' account' + ((s.accounts || 0) === 1 ? '' : 's'));
    var cov = r.coverage || {};
    var covText = 'Detection coverage could not be verified';
    if (cov.unverified > 0 && cov.blind > 0) { covText = cov.percent + '% of detection families are confirmed working, ' + cov.blind + ' are blind and ' + cov.unverified + ' unverified'; }
    else if (cov.blind > 0) { covText = cov.percent + '% of detection families are confirmed working and ' + cov.blind + ' are blind'; }
    else if (cov.unverified > 0) { covText = cov.percent + '% of detection families are confirmed working and ' + cov.unverified + ' could not be verified'; }
    else { covText = 'All ' + (cov.working || 0) + ' detection families are confirmed working'; }
    return parts.join(', ') + '. ' + covText + '.';
  }

  function section(title, node) {
    return S.ui.el('section', { class: 'report-section' }, [S.ui.el('h2', { text: title }), node]);
  }

  function simpleTable(headers, rows) {
    var tbody = S.ui.el('tbody');
    rows.forEach(function (r) {
      tbody.appendChild(S.ui.el('tr', {}, r.map(function (c) { return S.ui.el('td', { text: c === undefined || c === null || c === '' ? '-' : String(c) }); })));
    });
    return S.ui.el('table', { class: 'data' }, [
      S.ui.el('thead', {}, [S.ui.el('tr', {}, headers.map(function (h) { return S.ui.el('th', { text: h }); }))]),
      tbody
    ]);
  }

  function render(view, r) {
    S.ui.clear(view);
    var doc = S.ui.el('div', { class: 'report-doc' });
    var gen = r.generatedAt ? String(r.generatedAt).replace('T', ' ').slice(0, 16) : '';
    doc.appendChild(S.ui.el('div', { class: 'report-header' }, [
      S.ui.el('h1', { text: 'ALPHA Sentinel - Engagement Report' }),
      S.ui.el('div', { class: 'report-meta', text: 'Period ' + r.period.from + ' to ' + r.period.to + ' - generated by ' + r.generatedBy + ' at ' + gen + (r.demoData ? ' - DEMO DATA' : '') })
    ]));

    var exec = S.ui.el('p', { class: 'report-exec', text: summaryParagraph(r) });
    var lim = S.ui.el('p', { class: 'report-limitations', text: r.notes || '' });
    var cov = r.coverage || {};
    var limList = S.ui.el('ul', { class: 'timeline' });
    if (cov.unverified > 0) { limList.appendChild(S.ui.el('li', {}, [S.ui.el('span', { text: cov.unverified + ' rule family(ies) could NOT be verified: the audit policy was unreadable, so the alert counts may be understated.' })])); }
    if (cov.blind > 0) { limList.appendChild(S.ui.el('li', {}, [S.ui.el('span', { text: cov.blind + ' rule family(ies) are BLIND: Windows is not writing their events, so attacks in those families cannot appear in this report.' })])); }
    limList.appendChild(S.ui.el('li', {}, [S.ui.el('span', { text: 'Event data lives in memory since the process started; a restart clears it. Alert history survives in sentinel-history.csv.' })]));
    doc.appendChild(section('Executive summary', exec));
    doc.appendChild(section('Coverage and limitations', limList));

    /* three labelled groups: one unlabelled table mixing severities, statuses and
       tactics reads as if "New" were a severity. Each group keeps its own head. */
    var sevRows = Object.keys(r.summary.bySeverity || {}).map(function (k) { return [k, r.summary.bySeverity[k]]; });
    var statusRows = Object.keys(r.summary.byStatus || {}).map(function (k) { return [k, r.summary.byStatus[k]]; });
    var tacRows = Object.keys(r.summary.byTactic || {}).map(function (k) { return [k, r.summary.byTactic[k]]; });
    var findWrap = S.ui.el('div', { class: 'report-findings' });
    findWrap.appendChild(S.ui.el('h3', { class: 'report-sub', text: 'By severity' }));
    findWrap.appendChild(simpleTable(['Severity', 'Count'], sevRows));
    findWrap.appendChild(S.ui.el('h3', { class: 'report-sub', text: 'By status' }));
    findWrap.appendChild(simpleTable(['Status', 'Count'], statusRows));
    findWrap.appendChild(S.ui.el('h3', { class: 'report-sub', text: 'By tactic' }));
    findWrap.appendChild(simpleTable(['Tactic', 'Count'], tacRows));
    doc.appendChild(section('Findings', findWrap));

    var top = r.topAlerts || [];
    var topNode = top.length
      ? simpleTable(['Time', 'Severity', 'Title', 'Host', 'Account', 'Status'], top.map(function (a) {
          return [String(a.Time || '').replace('T', ' ').slice(0, 16), a.Severity, a.Title, a.Host || '-', a.Account || '-', a.Status || 'New'];
        }))
      : S.ui.el('p', { class: 'report-limitations', text: 'No alerts in this period.' });
    doc.appendChild(section('Top alerts', topNode));

    var chainNode;
    if (!(r.chains || []).length) { chainNode = S.ui.el('p', { class: 'report-limitations', text: 'No multi-step activity detected in this period.' }); }
    else {
      var rows = (r.chains || []).map(function (c) {
        return [c.title, String((c.alerts || []).length), c.maxSeverity, (c.tacticsInOrder || []).join(' > ')];
      });
      chainNode = simpleTable(['Chain', 'Alerts', 'Max severity', 'Tactics in order'], rows);
    }
    doc.appendChild(section('Attack chains', chainNode));

    var assets = r.assets || [];
    var assetNode = assets.length
      ? simpleTable(['Asset', 'Kind', 'Alerts', 'Max severity'], assets.map(function (a) { return [a.name || a.address, a.kind, String(a.alertCount || 0), a.maxSeverity || '-']; }))
      : S.ui.el('p', { class: 'report-limitations', text: 'No assets with alerts in this period.' });
    doc.appendChild(section('Affected assets', assetNode));

    var rem = r.remediation || [];
    var remNode = rem.length
      ? simpleTable(['Rule', 'Recommendation', 'Alerts'], rem.map(function (x) { return [x.rule, x.recommendation, String(x.count)]; }))
      : S.ui.el('p', { class: 'report-limitations', text: 'Nothing to remediate in this period.' });
    doc.appendChild(section('Remediation checklist', remNode));

    var tl = r.timeline || [];
    var tlNode = tl.length
      ? simpleTable(['Time', 'Severity', 'Title', 'Host', 'Account', 'Status'], tl.map(function (a) {
          return [String(a.Time || '').replace('T', ' ').slice(0, 16), a.Severity, a.Title, a.Host || '-', a.Account || '-', a.Status || 'New'];
        }))
      : S.ui.el('p', { class: 'report-limitations', text: 'No alerts in this period.' });
    doc.appendChild(section('Appendix - alert timeline', tlNode));
    view.appendChild(doc);
  }

  function load(from, to) {
    return S.api.get('/api/report' + S.api.qs({ from: from, to: to }), 'reports').then(function (r) {
      report = r; errorMsg = '';
      var view = document.getElementById('view');
      if (view && S.router.current() === 'reports') { render(view, r); }
    }).catch(function (err) {
      errorMsg = err && err.message ? err.message : 'request failed';
      var view = document.getElementById('view');
      if (view && S.router.current() === 'reports') {
        S.ui.clear(view);
        view.appendChild(S.ui.error('Could not generate the report: ' + errorMsg));
      }
    });
  }

  function controls() {
    var d = defaults();
    var from = S.ui.el('input', { class: 'field', type: 'date', value: d.from, id: 'reportFrom' });
    var to = S.ui.el('input', { class: 'field', type: 'date', value: d.to, id: 'reportTo' });
    var go = S.ui.el('button', { class: 'btn btn-primary', text: 'Generate', type: 'button' });
    var print = S.ui.el('button', { class: 'btn', text: 'Print / Save as PDF', type: 'button' });
    go.addEventListener('click', function () { load(from.value, to.value); });
    print.addEventListener('click', function () { window.print(); });
    return S.ui.el('div', { class: 'filterbar no-print' }, [
      S.ui.el('span', { class: 'caption', text: 'From' }), from,
      S.ui.el('span', { class: 'caption', text: 'to' }), to, go,
      S.ui.el('span', { class: 'grow spacer' }), print
    ]);
  }

  S.pages.reports = {
    title: 'Reports',
    subtitle: 'A printable engagement report generated from observed data only.',
    render: function () {
      var view = document.getElementById('view');
      S.ui.clear(view);
      view.appendChild(controls());
      if (report) { render(view, report); }
      else {
        var d = defaults();
        view.appendChild(S.ui.el('div', { class: 'state no-print' }, [S.ui.el('div', { class: 'state-title', text: 'Pick a range and generate the report.' })]));
        load(d.from, d.to);
      }
    },
    refresh: function () { },
    filter: function () { }
  };
})();
